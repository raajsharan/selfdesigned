-- ------------------------------------------------------------------ user-defined pages
-- Nothing is pre-created: administrators design every page. A page is either
--   records : owns data, with its own fields, form layout and table layout
--   view    : a read-mostly table fed by any number of records pages ("All records")
-- Field definitions and layouts live in inventory_pages.config (validated by the API).
CREATE TABLE IF NOT EXISTS inventory_pages (
  id          SERIAL PRIMARY KEY,
  slug        VARCHAR(48) UNIQUE NOT NULL,          -- immutable; used in URLs and permission keys (page:<slug>)
  title       VARCHAR(96) NOT NULL,
  kind        VARCHAR(8) NOT NULL DEFAULT 'records' CHECK (kind IN ('records', 'view')),
  icon        VARCHAR(32) NOT NULL DEFAULT 'database',
  description TEXT,
  config      JSONB NOT NULL DEFAULT '{}',
  sort_order  INT NOT NULL DEFAULT 0,
  created_by  INT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- One table for every page's records. All field values live in `data`. Fields an administrator marks with a
-- semantic role (name, ip, mac, asset tag, status, ...) are also copied into the promoted columns below so
-- cross-page features (uniqueness, decommission, search, reports, reconcile) can query them directly.
CREATE TABLE IF NOT EXISTS inventory_records (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  page_id           INT NOT NULL REFERENCES inventory_pages(id) ON DELETE CASCADE,
  data              JSONB NOT NULL DEFAULT '{}',
  secrets           JSONB NOT NULL DEFAULT '{}',     -- password-type fields, AES-256-GCM encrypted
  vm_name           VARCHAR(255),
  hostname          VARCHAR(255),
  ip_address        VARCHAR(64),
  mac_address       VARCHAR(64),
  asset_tag         VARCHAR(64),
  server_status     VARCHAR(64),
  os_type           VARCHAR(128),
  department        VARCHAR(128),
  location          VARCHAR(128),
  asset_owner       VARCHAR(255),
  patching_type     VARCHAR(64),
  last_patched_at   DATE,
  is_deleted        BOOLEAN NOT NULL DEFAULT FALSE,
  deleted_at        TIMESTAMPTZ,
  deleted_by        INT,
  is_decommissioned BOOLEAN NOT NULL DEFAULT FALSE,
  decommissioned_at TIMESTAMPTZ,
  created_by        INT,
  updated_by        INT,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_records_page   ON inventory_records (page_id, is_deleted, is_decommissioned);
CREATE INDEX IF NOT EXISTS idx_records_mac    ON inventory_records (upper(mac_address));
CREATE INDEX IF NOT EXISTS idx_records_ip     ON inventory_records (ip_address);
CREATE INDEX IF NOT EXISTS idx_records_tag    ON inventory_records (asset_tag);

-- Permanent decommission log. Rows survive asset deletion and cannot be edited or
-- removed; only the reactivated_* columns may be filled in.
CREATE TABLE IF NOT EXISTS decommission_log (
  id                      BIGSERIAL PRIMARY KEY,
  source                  VARCHAR(48) NOT NULL,
  asset_id                BIGINT NOT NULL,
  asset_name              VARCHAR(255),
  asset_snapshot          JSONB NOT NULL,
  asset_tag               VARCHAR(64),
  ip_address              VARCHAR(64),
  reason                  TEXT,
  decommissioned_by_id    INT,
  decommissioned_by_email VARCHAR(255),
  decommissioned_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  reactivated_by_id       INT,
  reactivated_by_email    VARCHAR(255),
  reactivated_at          TIMESTAMPTZ
);

CREATE OR REPLACE FUNCTION decommission_log_guard() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'decommission_log is immutable: rows cannot be deleted';
  END IF;
  IF ROW(NEW.id, NEW.source, NEW.asset_id, NEW.asset_name, NEW.asset_snapshot, NEW.asset_tag, NEW.ip_address,
         NEW.reason, NEW.decommissioned_by_id, NEW.decommissioned_by_email, NEW.decommissioned_at)
     IS DISTINCT FROM
     ROW(OLD.id, OLD.source, OLD.asset_id, OLD.asset_name, OLD.asset_snapshot, OLD.asset_tag, OLD.ip_address,
         OLD.reason, OLD.decommissioned_by_id, OLD.decommissioned_by_email, OLD.decommissioned_at) THEN
    RAISE EXCEPTION 'decommission_log is immutable: only reactivation fields may change';
  END IF;
  IF OLD.reactivated_at IS NOT NULL THEN
    RAISE EXCEPTION 'decommission_log row already closed';
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_decommission_log_guard ON decommission_log;
CREATE TRIGGER trg_decommission_log_guard BEFORE UPDATE OR DELETE ON decommission_log
  FOR EACH ROW EXECUTE FUNCTION decommission_log_guard();

