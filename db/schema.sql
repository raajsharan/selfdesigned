  vm_name          VARCHAR(255) NOT NULL,
  ip_address       VARCHAR(64),
  os               VARCHAR(255),
  cluster          VARCHAR(128),
  datacenter       VARCHAR(128),
  esxi_host        VARCHAR(255),
