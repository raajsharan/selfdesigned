  can_view_passwords BOOLEAN NOT NULL DEFAULT FALSE,
  page_overrides     JSONB NOT NULL DEFAULT '{}',
  last_login_at      TIMESTAMPTZ,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
