  project_id               INT NOT NULL REFERENCES migration_projects(id) ON DELETE CASCADE,
  host_name                VARCHAR(255) NOT NULL,
  datacenter               VARCHAR(128),
  cluster                  VARCHAR(128),
  vcenter                  VARCHAR(255),
  vms_vacate_status        VARCHAR(32) NOT NULL DEFAULT 'Not Started',
  proxmox_install_status   VARCHAR(32) NOT NULL DEFAULT 'Not Started',
  vm_migration_back_status VARCHAR(32) NOT NULL DEFAULT 'Not Started',
  idrac_ip                 VARCHAR(64),
  idrac_username           VARCHAR(128),
  idrac_password_encrypted TEXT,
  license_expiry           DATE,
  notes                    TEXT,
  custom                   JSONB NOT NULL DEFAULT '{}',
  created_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (project_id, host_name)
);

CREATE TABLE IF NOT EXISTS migration_vms (
