-- ---------------------------------------------------------------- Migration tracker
CREATE TABLE IF NOT EXISTS migration_projects (
  id          SERIAL PRIMARY KEY,
  name        VARCHAR(255) NOT NULL UNIQUE,
  description TEXT,
  tabs        JSONB NOT NULL DEFAULT '[]',
  is_active   BOOLEAN NOT NULL DEFAULT TRUE,
  created_by  INT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS migration_custom_fields (
  id         SERIAL PRIMARY KEY,
  project_id INT NOT NULL REFERENCES migration_projects(id) ON DELETE CASCADE,
  key        VARCHAR(48) NOT NULL,
  label      VARCHAR(128) NOT NULL,
  type       VARCHAR(16) NOT NULL DEFAULT 'text',   -- text|textarea|number|boolean|dropdown|date
  options    JSONB NOT NULL DEFAULT '[]',
  tab_keys   JSONB NOT NULL DEFAULT '[]',           -- empty = every tab
  sort_order INT NOT NULL DEFAULT 0,
  UNIQUE (project_id, key)
);

CREATE TABLE IF NOT EXISTS migration_hosts (
